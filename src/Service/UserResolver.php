namespace AvalynxOfficeEas\Service;

use AvalynxOfficeEas\Db\Model\Account;
use AvalynxOfficeEas\Db\Model\User;
use AvalynxOfficeEas\Db\Model\UserAppPassword;
use AvalynxOfficeEas\Dto\EasUserContext;
use Doctrine\ORM\EntityManagerInterface;

/**
 * Resolves an EAS login (application user e-mail address) to the user and
 * every account assigned to them, and verifies the credentials against the
 * user's device/app passwords (profile → app passwords in the web app).
 *
 * The web login password is deliberately NOT accepted: it would be stored
 * on every device and could not be revoked per device. App passwords are
 * generated by the core, stored as password_hash() digests and can be
 * revoked individually.
 *
 * Mailbox or alias addresses are intentionally not accepted as usernames:
 * a device session always belongs to a user, never to a single account.
 */
final readonly class UserResolver
{
    /**
     * bcrypt hash of a random string; verified for unknown users so that the
     * response time does not reveal whether an e-mail address exists.
     */
    private const string DUMMY_PASSWORD_HASH = '$2y$13$aBry3ZNLyuzkWjsUI3dEd.XX.4Sxbae/wOuvT.vugjuAaRr23o1LG';

    public function __construct(private EntityManagerInterface $entityManager)
    {
    }

    public function resolve(string $username, string $password): ?EasUserContext
    {
        $email = mb_strtolower(trim($username));

        if ('' === $email) {
            return null;
        }

        $user = $this->entityManager->createQueryBuilder()
            ->select('u')
            ->from(User::class, 'u')
            ->where('LOWER(u.email) = :email')
            ->andWhere('u.active = true')
            ->setParameter('email', $email)
            ->setMaxResults(1)
            ->getQuery()
            ->getOneOrNullResult();

        \assert($user instanceof User || null === $user);

        if (null === $user) {
            // constant-time behaviour: run the same hash check as for known users
            password_verify($password, self::DUMMY_PASSWORD_HASH);

            return null;
        }

        $appPassword = $this->matchAppPassword($user, $password);

        if (null === $appPassword) {
            return null;
        }

        $this->touchAppPassword($appPassword);

        return new EasUserContext($user, $this->accountsForUser($user));
    }

    /**
     * Normalizes a password typed on a device the same way the core does
     * when hashing it: dashes and whitespace are optional, case is ignored.
     */
    public static function normalizePassword(string $password): string
    {
        return mb_strtolower((string) preg_replace('/[\s-]+/', '', $password));
    }

    /**
     * Checks the password against every active app password of the user.
     * All candidates are verified (no early return) so that the number of
     * app passwords does not leak through timing; when the user has none, a
     * dummy verification keeps the response time comparable.
     */
    private function matchAppPassword(User $user, string $password): ?UserAppPassword
    {
        $normalized = self::normalizePassword($password);

        /** @var list<UserAppPassword> $candidates */
        $candidates = $this->entityManager->createQueryBuilder()
            ->select('p')
            ->from(UserAppPassword::class, 'p')
            ->where('p.user = :user')
            ->andWhere('p.revokedAt IS NULL')
            ->setParameter('user', $user)
            ->getQuery()
            ->getResult();

        if ([] === $candidates) {
            password_verify($normalized, self::DUMMY_PASSWORD_HASH);

            return null;
        }

        $match = null;

        foreach ($candidates as $candidate) {
            if (password_verify($normalized, $candidate->getPasswordHash()) && null === $match) {
                $match = $candidate;
            }
        }

        return $match;
    }

    /**
     * Records the last use at most once per minute to keep the sync traffic
     * from turning into a write per request.
     */
    private function touchAppPassword(UserAppPassword $appPassword): void
    {
        $now = new \DateTimeImmutable('now', new \DateTimeZone('UTC'));
        $lastUsed = $appPassword->getLastUsedAt();

        if (null !== $lastUsed && $now->getTimestamp() - $lastUsed->getTimestamp() < 60) {
            return;
        }

        try {
            $this->entityManager->getConnection()->executeStatement(
                'UPDATE app_user_app_password SET last_used_at = :now WHERE id = :id AND revoked_at IS NULL',
                ['now' => $now->format('Y-m-d H:i:s'), 'id' => $appPassword->getId()?->toRfc4122()],
            );
            $appPassword->setLastUsedAt($now);
        } catch (\Throwable $e) {
            error_log('EAS: failed to record app password usage: '.$e->getMessage());
        }
    }

    /**
     * Every account assigned to the user, sorted by e-mail address — the
     * same set the web UI shows after the login.
     *
     * @return list<Account>
     */
    private function accountsForUser(User $user): array
    {
        $rows = $this->entityManager->getConnection()->fetchAllAssociative(
            'SELECT a.id FROM user_account ul JOIN account a ON a.id = ul.account_id WHERE ul.user_id = :userId ORDER BY a.email ASC',
            ['userId' => $user->getId()?->toRfc4122()],
        );

        $accounts = [];

        foreach ($rows as $row) {
            $id = $row['id'] ?? null;

            if (is_string($id) && '' !== $id) {
                $account = $this->entityManager->find(Account::class, $id);

                if (null !== $account) {
                    $accounts[] = $account;
                }
            }
        }

        return $accounts;
    }
}
